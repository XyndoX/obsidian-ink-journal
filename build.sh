#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"
[ -f theme.src.css ] || { echo "build.sh: theme.src.css missing" >&2; exit 1; }
# Parts are concatenated in this order; later parts may override earlier ones.
PARTS=(fonts.css theme.src.css plugins-nav.css plugins-content.css snippets.css)
{
  echo "/* Journal — Obsidian theme: pen-on-paper skin. GENERATED by build.sh, do not edit. */"
  echo "/* Edit theme.src.css (core), plugins-*.css, snippets.css; fonts.css embeds Kalam + Patrick Hand (SIL OFL). */"
  echo "/* https://github.com/XyndoX/obsidian-journal-theme */"
  for f in "${PARTS[@]}"; do
    [ -f "$f" ] && { echo; echo "/* ===== $f ===== */"; cat "$f"; }
  done
} > theme.css
echo "theme.css: $(wc -c < theme.css) bytes"
# Optional local install: JOURNAL_VAULT=/path/to/vault ./build.sh (Obsidian hot-reloads the active theme's CSS).
if [ -n "${JOURNAL_VAULT:-}" ]; then
  mkdir -p "$JOURNAL_VAULT/.obsidian/themes/Journal"
  cp manifest.json theme.css "$JOURNAL_VAULT/.obsidian/themes/Journal/"
  echo "installed → $JOURNAL_VAULT/.obsidian/themes/Journal"
fi
